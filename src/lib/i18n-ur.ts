const DAY_UR: Record<string, string> = { Mon: 'Peer', Tue: 'Mangal', Wed: 'Budh', Thu: 'Jumeraat', Fri: 'Jumma', Sat: 'Hafta', Sun: 'Itwaar' };

export const UR_PATTERNS: [RegExp, (m: RegExpMatchArray) => string | null][] = [
  [/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun), (.+)$/, (m) => DAY_UR[m[1]] + ', ' + m[2]],
  [/^· (\d+) pending$/, (m) => `· ${m[1]} baqi`],
  [/^(\d+) pending$/, (m) => `${m[1]} baqi`],
  [/^Progress (\d+)%$/, (m) => `Taraqqi ${m[1]}%`],
  [/^Is mahine rank #(\d+)$/, (m) => `Is mahine darja #${m[1]}`],
  [/^e\.g\. (.+)$/, (m) => 'misal: ' + m[1]]
];
